class FFTLocation:
    name: str
    requirements: list[Requirement]
    battle_level: int

    def __init__(self, name: "LocationNames", requirements: list[Requirement | type[Requirement]] = None, battle_level: int = None):
        if requirements is None:
            requirements = list()
        self.name = name.value
        self.requirements = requirements
        assert battle_level is not None, self.name
        self.battle_level = battle_level

    def __repr__(self):
        return f"{self.__class__} -- {self.name}"

    def check_enabled(self, options: FinalFantasyTacticsIIOptions):
        return True

class SidequestLocation(FFTLocation):
    def check_enabled(self, options: FinalFantasyTacticsIIOptions):
        return options.sidequest_battles

class RareBattleLocation(FFTLocation):
    def check_enabled(self, options: FinalFantasyTacticsIIOptions):
        return options.rare_battles

class VanillaFinalFightsLocation(FFTLocation):
    def check_enabled(self, options: FinalFantasyTacticsIIOptions):
        return options.final_battles == options.final_battles.option_vanilla

class AltimaOnlyFinalFightLocation(FFTLocation):
    def check_enabled(self, options: FinalFantasyTacticsIIOptions):
        return options.final_battles == options.final_battles.option_altima_only

class MoveFindItemLocation(FFTLocation):
    def check_enabled(self, options: FinalFantasyTacticsIIOptions):
        return options.move_find_item_locations

class LavaMoveFindItemLocation(MoveFindItemLocation):
    def check_enabled(self, options: FinalFantasyTacticsIIOptions):
        return (super().check_enabled(options)
                and options.move_find_item_location_logic != options.move_find_item_location_logic.option_vanilla)

class SidequestMoveFindItemLocation(MoveFindItemLocation):
    def check_enabled(self, options: FinalFantasyTacticsIIOptions):
        return super().check_enabled(options)  and options.sidequest_battles

class VanillaFinalFightMoveFindItemLocation(MoveFindItemLocation):
    def check_enabled(self, options: FinalFantasyTacticsIIOptions):
        return (options.final_battles == options.final_battles.option_vanilla) and super().check_enabled(options)

class AltimaOnlyFinalFightMoveFindItemLocation(MoveFindItemLocation):
    def check_enabled(self, options: FinalFantasyTacticsIIOptions):
        return (options.final_battles == options.final_battles.option_altima_only) and super().check_enabled(options)

